// Word rules for putting a receipt line into a category. They run against the item name as the
// parser leaves it (upper case, no accents) and know common English and French words, receipt
// abbreviations (VSL = vaisselle, DCHE = douche, CHKN = chicken) and brands sold in Mauritius.
// Order matters: the first rule that matches wins, so specific signals come before broad ones
// ("MAGGI CHICKEN CUBE" is a stock cube, not chicken; "EAU DE COLOGNE" is not water).

type Rule = readonly [categoryId: string, pattern: RegExp];

const words = (list: string) => new RegExp(`\\b(?:${list.trim().split(/\s*\|\s*/).join('|')})\\b`);

